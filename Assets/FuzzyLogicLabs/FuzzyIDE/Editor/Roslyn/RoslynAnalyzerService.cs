    /// <summary>
    /// A decoupled service that performs asynchronous C# code parsing and semantic analysis
    /// using Microsoft.CodeAnalysis (Roslyn) without blocking the main thread.
    /// </summary>
    public class RoslynAnalyzerService
    {
        // Immutable state class ensures thread-safe atomic swaps when new code is compiled
        private class AnalysisState
        {
            public SyntaxTree Tree { get; }
            public CSharpCompilation Compilation { get; }
            public SemanticModel Model { get; }

            public AnalysisState(SyntaxTree tree, CSharpCompilation compilation, SemanticModel model)
            {
                Tree = tree;
                Compilation = compilation;
                Model = model;
            }
        }

        // Volatile reference ensures cross-thread visibility immediately after compilation
        private volatile AnalysisState _currentState;

        // Updates can finish out of order; only the newest one may become the current state.
        private long _updateSequence;
        private long _publishedSequence;
        private readonly object _publishGate = new object();

        public static IEnumerable<string> ActiveDefines { get; set; } = new string[0];

        /// <summary>True when the current state comes from the shared project compilation (all files of the assembly).</summary>
        public bool IsProjectAnalysis { get; private set; }

        private void PublishState(long sequence, AnalysisState state, bool isProjectAnalysis)
        {
            lock (_publishGate)
            {
                if (sequence < _publishedSequence) return;
                _publishedSequence = sequence;
                IsProjectAnalysis = isProjectAnalysis;
                _currentState = state;
            }
        }

        /// <summary>
        /// Builds a Semantic Model for the code asynchronously. Files that belong to a Unity script assembly are analysed
        /// against the shared <see cref="ProjectCompilationCache"/>; anything else falls back to a standalone compilation
        /// over the given references.
        /// </summary>
        public Task UpdateCodeAsync(string code, string filePath, IEnumerable<string> referenceAssemblyPaths, CancellationToken cancellationToken = default)
        {
            long sequence = Interlocked.Increment(ref _updateSequence);
            return Task.Run(() =>
            {
                if (cancellationToken.IsCancellationRequested) return;

                if (ProjectCompilationCache.TryUpdateDocument(filePath, code, out var projectTree, out var projectCompilation))
                {
                    PublishState(sequence, new AnalysisState(projectTree, projectCompilation, projectCompilation.GetSemanticModel(projectTree)), true);
                    return;
                }

                var parseOptions = CSharpParseOptions.Default.WithPreprocessorSymbols(ActiveDefines);
                var syntaxTree = CSharpSyntaxTree.ParseText(code ?? string.Empty, parseOptions, path: filePath ?? "");

                // 2. Create MetadataReferences
                var references = new List<MetadataReference>();
                var addedPaths = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                if (referenceAssemblyPaths != null)
                {
                    foreach (var path in referenceAssemblyPaths)
                    {
                        if (string.IsNullOrEmpty(path) || !addedPaths.Add(path)) continue;
                        try
                        {
                            var metaRef = ProjectCompilationCache.GetMetadataReference(path);
                            references.Add(metaRef);
                        }
                        catch
                        {
                            // Safely ignore invalid or missing assembly paths
                        }
                    }
                }

                try
                {
                    var goLocation = UnityCompat.GetAssemblyPath(typeof(UnityEngine.GameObject).Assembly);
                    if (!string.IsNullOrEmpty(goLocation) && addedPaths.Add(goLocation))
                    {
                        references.Add(ProjectCompilationCache.GetMetadataReference(goLocation));
                    }

                    var dbgLocation = UnityCompat.GetAssemblyPath(typeof(UnityEngine.Debug).Assembly);
                    if (!string.IsNullOrEmpty(dbgLocation) && addedPaths.Add(dbgLocation))
                    {
                        references.Add(ProjectCompilationCache.GetMetadataReference(dbgLocation));
                    }
                }
                catch { }

                // 3. Create a CSharpCompilation
                var trees = new List<SyntaxTree> { syntaxTree };
                
                if (!string.IsNullOrEmpty(filePath))
                {
                    try
                    {
                        string dir = System.IO.Path.GetDirectoryName(filePath);
                        string fileName = System.IO.Path.GetFileName(filePath);
                        string baseName = fileName.Split('.')[0];
                        if (!string.IsNullOrEmpty(dir) && System.IO.Directory.Exists(dir))
                        {
                            var otherFiles = System.IO.Directory.GetFiles(dir, baseName + "*.cs");
                            foreach (var file in otherFiles)
                            {
                                if (file != filePath)
                                {
                                    string text = System.IO.File.ReadAllText(file);
                                    trees.Add(CSharpSyntaxTree.ParseText(text, parseOptions, path: file));
                                }
                            }
                        }
                    }
                    catch { }
                }

                var compilationOptions = new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary)
                    .WithSpecificDiagnosticOptions(new Dictionary<string, ReportDiagnostic> { 
                        { "CS0436", ReportDiagnostic.Suppress },
                        { "CS0433", ReportDiagnostic.Suppress }
                    });
                var compilation = CSharpCompilation.Create(
                    "VirtualIDEAssembly",
                    trees,
                    references,
                    compilationOptions);

                // 4. Generate the SemanticModel
                var semanticModel = compilation.GetSemanticModel(syntaxTree);

                if (cancellationToken.IsCancellationRequested) return;
                PublishState(sequence, new AnalysisState(syntaxTree, compilation, semanticModel), false);
            });
        }

        /// <summary>
        /// Uses the Semantic Model to infer the type or symbol name at the given character index asynchronously.
        /// </summary>
        public Task<string> GetTypeAtPositionAsync(int characterIndex)
        {
            return Task.Run(() =>
            {
                // Capture current state safely
                var state = _currentState;
                if (state == null || state.Model == null)
                    return null;

                var root = state.Tree.GetRoot();

                // Validate bounds
                if (characterIndex < 0 || characterIndex > root.FullSpan.End)
                    return null;

                // Find the syntax token at the specific character position
                var token = root.FindToken(characterIndex);
                var node = token.Parent;

                if (node == null)
                    return null;

                // 1. Try to get direct Type Information (e.g. for variable declarations)
                var typeInfo = state.Model.GetTypeInfo(node);
                if (typeInfo.Type != null && typeInfo.Type.Kind != SymbolKind.ErrorType)
                {
                    return typeInfo.Type.ToDisplayString();
                }

                // 2. Try to get Symbol Information (e.g. for method calls, properties, or class references)
                var symbolInfo = state.Model.GetSymbolInfo(node);
                if (symbolInfo.Symbol != null)
                {
                    return symbolInfo.Symbol.ToDisplayString();
                }

                // Could not resolve a semantic type or symbol
                return null;
            });
        }

        private CompletionKind MapSymbolKind(ISymbol symbol)
        {
            if (symbol is INamedTypeSymbol namedType)
            {
                switch (namedType.TypeKind)
                {
                    case TypeKind.Class: return CompletionKind.Class;
                    case TypeKind.Interface: return CompletionKind.Interface;
                    case TypeKind.Struct: return CompletionKind.Struct;
                    case TypeKind.Enum: return CompletionKind.Enum;
                }
            }

            switch (symbol.Kind)
            {
                case SymbolKind.Method: return CompletionKind.Method;
                case SymbolKind.Property: return CompletionKind.Property;
                case SymbolKind.Field: return CompletionKind.Field;
                case SymbolKind.Parameter: return CompletionKind.Parameter;
                case SymbolKind.Local: return CompletionKind.Variable;
                case SymbolKind.NamedType: return CompletionKind.Class;
            }
            return CompletionKind.Other;
        }

        private int GetCompletionPriority(CompletionItem item)
        {
            if (item.Kind == CompletionKind.Variable || item.Kind == CompletionKind.Parameter) return 100;
            if (item.Kind == CompletionKind.Field || item.Kind == CompletionKind.Property) return 90;
            if (item.Kind == CompletionKind.Method) return 80;
            if (item.Kind == CompletionKind.Snippet) return 70;
            if (item.Kind == CompletionKind.Keyword) return 60;
            
            if (item.NamespaceHint != null)
            {
                if (item.NamespaceHint.StartsWith("System")) return 10;
                if (item.NamespaceHint.StartsWith("UnityEngine") || item.NamespaceHint.StartsWith("UnityEditor")) return 50;
                return 40; 
            }
            
            if (item.Kind == CompletionKind.Class || item.Kind == CompletionKind.Struct || item.Kind == CompletionKind.Interface || item.Kind == CompletionKind.Enum)
                return 45; // Local / Same namespace types
                
            return 30;
        }

        private string ExtractSummary(string xml)
        {
            if (string.IsNullOrEmpty(xml)) return "";
            var match = System.Text.RegularExpressions.Regex.Match(xml, @"<summary>\s*(.*?)\s*</summary>", System.Text.RegularExpressions.RegexOptions.Singleline);
            if (match.Success)
            {
                string summary = match.Groups[1].Value.Trim();
                summary = System.Text.RegularExpressions.Regex.Replace(summary, @"\s+", " ");
                summary = System.Text.RegularExpressions.Regex.Replace(summary, @"<para\s*/>", "\n");
                summary = System.Text.RegularExpressions.Regex.Replace(summary, @"<see cref=""([^""]+)""\s*/>", "$1");
                return summary;
            }
            return "";
        }

        /// <summary>
        /// Analyzes the expression immediately preceding the dot token and returns accessible public members.
        /// </summary>
        public Task<List<CompletionItem>> GetCompletionsAsync(string code, int caretPosition)
        {
            return Task.Run(() =>
            {
                var completions = new List<CompletionItem>();
                var state = _currentState;
                if (state == null) return completions;

                // Create a fast updated compilation
                var newText = Microsoft.CodeAnalysis.Text.SourceText.From(code ?? string.Empty);
                var syntaxTree = state.Tree.WithChangedText(newText);
                var compilation = state.Compilation.ReplaceSyntaxTree(state.Tree, syntaxTree);
                var semanticModel = compilation.GetSemanticModel(syntaxTree);
                if (semanticModel == null) return completions;

                var root = syntaxTree.GetRoot();

                // Safety bound check
                if (caretPosition < 0 || caretPosition > root.FullSpan.End) return completions;

                // Grab the token immediately behind the caret (e.g. the '.')
                var token = root.FindToken(Math.Max(0, caretPosition - 1));

                // We want the dot token. If we somehow hit something else, 
                // it might mean they typed a letter. Traverse up to MemberAccessExpression.
                var node = token.Parent;
                MemberAccessExpressionSyntax memberAccess = null;

                while (node != null)
                {
                    if (node is MemberAccessExpressionSyntax ma && ma.OperatorToken.SpanStart <= caretPosition)
                    {
                        memberAccess = ma;
                        break;
                    }
                    node = node.Parent;
                }

                if (memberAccess != null)
                {
                    var typeInfo = semanticModel.GetTypeInfo(memberAccess.Expression);
                    var symbolInfo = semanticModel.GetSymbolInfo(memberAccess.Expression);
                    
                    var symbol = symbolInfo.Symbol ?? symbolInfo.CandidateSymbols.FirstOrDefault();
                    
                    if (symbol is INamespaceSymbol namespaceSymbol)
                    {
                        foreach (var member in namespaceSymbol.GetMembers())
                        {
                            if (member is INamedTypeSymbol namedType && namedType.DeclaredAccessibility == Accessibility.Public)
                            {
                                string sig = namedType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                                completions.Add(new CompletionItem(namedType.Name, MapSymbolKind(namedType), null, null, sig));
                            }
                            else if (member is INamespaceSymbol childNamespace)
                            {
                                string sig = childNamespace.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                                completions.Add(new CompletionItem(childNamespace.Name, CompletionKind.Other, null, null, sig));
                            }
                        }
                    }
                    else
                    {
                        bool isStaticAccess = false;
                        var typeSymbol = typeInfo.Type;
                        
                        if (symbol is INamedTypeSymbol namedTypeSymbol)
                        {
                            typeSymbol = namedTypeSymbol;
                            isStaticAccess = true;
                        }
                        else if (typeSymbol == null || typeSymbol.Kind == SymbolKind.ErrorType)
                        {
                            typeSymbol = symbol as INamedTypeSymbol;
                        }

                        if (typeSymbol != null && typeSymbol.Kind != SymbolKind.ErrorType)
                        {
                            var currentType = typeSymbol;
                            while (currentType != null)
                            {
                                foreach (var member in currentType.GetMembers())
                                {
                                    if (member.DeclaredAccessibility == Accessibility.Public && !member.IsImplicitlyDeclared)
                                    {
                                        if (isStaticAccess && !member.IsStatic) continue;
                                        if (!isStaticAccess && member.IsStatic) continue;

                                        if (member.Name == "GetHashCode" || member.Name == "Equals" ||
                                            member.Name == "GetType" || member.Name == "ReferenceEquals" ||
                                            member.Name == "ToString")
                                            continue;

                                        if (member.Kind == SymbolKind.Method && ((IMethodSymbol)member).MethodKind != MethodKind.Ordinary)
                                            continue;

                                        if (member.Name.Contains("<") || member.Name.Contains(">")) continue;
                                        if (member.GetAttributes().Any(ad => ad.AttributeClass?.Name == "ObsoleteAttribute" || ad.AttributeClass?.Name == "Obsolete")) continue;

                                        string sig = member.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                                        completions.Add(new CompletionItem(member.Name, MapSymbolKind(member), null, null, sig));
                                    }
                                }
                                currentType = currentType.BaseType;
                            }
                        }
                    }
                }
                else
                {
                    // Provide Unity magic methods if freely typing in the class body
                    string[] unityMethods = new string[] {
                        "Awake", "Start", "Update", "FixedUpdate", "LateUpdate",
                        "OnEnable", "OnDisable", "OnDestroy",
                        "OnTriggerEnter", "OnTriggerStay", "OnTriggerExit",
                        "OnCollisionEnter", "OnCollisionStay", "OnCollisionExit",
                        "OnGUI", "OnDrawGizmos", "OnDrawGizmosSelected"
                    };
                    foreach (var um in unityMethods)
                        completions.Add(new CompletionItem(um, CompletionKind.Method));
                }

                return completions.GroupBy(x => x.Name).Select(g => g.First()).OrderByDescending(x => GetCompletionPriority(x)).ThenBy(x => x.Name).ToList();
            });
        }

        private static readonly string[] CSHARP_KEYWORDS = new string[] {
            "using", "namespace", "class", "public", "private", "protected", "internal",
            "void", "int", "string", "bool", "float", "double", "object", "var",
            "return", "if", "else", "for", "foreach", "while", "do", "switch", "case", "break", "continue",
            "new", "this", "base", "true", "false", "null", "typeof", "default"
        };

        private static Dictionary<string, string> _unimportedTypesCache = null;

        private void BuildUnimportedTypesCache(Compilation compilation)
        {
            if (_unimportedTypesCache != null) return;

            var cache = new Dictionary<string, string>();
            foreach (var reference in compilation.References)
            {
                var symbol = compilation.GetAssemblyOrModuleSymbol(reference) as IAssemblySymbol;
                if (symbol != null) AddNamespacesToCache(symbol.GlobalNamespace, cache);
            }
            AddNamespacesToCache(compilation.GlobalNamespace, cache);
            _unimportedTypesCache = cache;
        }

        private void AddNamespacesToCache(INamespaceSymbol ns, Dictionary<string, string> cache)
        {
            if (ns == null) return;
            foreach (var type in ns.GetTypeMembers())
            {
                if (type.DeclaredAccessibility == Accessibility.Public && !type.Name.Contains("<"))
                {
                    string nsName = ns.ToDisplayString();
                    if (!string.IsNullOrEmpty(nsName) && nsName != "<global namespace>")
                    {
                        if (!cache.ContainsKey(type.Name)) cache[type.Name] = nsName;
                    }
                }
            }
            foreach (var child in ns.GetNamespaceMembers())
            {
                AddNamespacesToCache(child, cache);
            }
        }

        /// <summary>
        /// Project names (tags, layers, scenes, animator states...) when the caret is inside a string literal passed to
        /// a Unity API that expects one; null otherwise.
        /// </summary>
        public Task<UnityStringCompletionResult> GetUnityStringCompletionsAsync(string code, int caretPosition, UnityProjectSnapshot snapshot)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                var syntaxTree = state != null
                    ? state.Tree.WithChangedText(Microsoft.CodeAnalysis.Text.SourceText.From(code ?? string.Empty))
                    : CSharpSyntaxTree.ParseText(code ?? string.Empty);
                SemanticModel model = null;
                if (state != null)
                {
                    try { model = state.Compilation.ReplaceSyntaxTree(state.Tree, syntaxTree).GetSemanticModel(syntaxTree); }
                    catch (ArgumentException) { model = null; }
                }

                var kind = UnityStringContext.GetContext(syntaxTree.GetRoot(), model, caretPosition, out var literal);
                if (kind == UnityStringKind.None) return null;

                string category = UnityStringContext.Describe(kind);
                var items = new List<CompletionItem>();
                foreach (var value in snapshot.GetValues(kind).OrderBy(v => v, StringComparer.OrdinalIgnoreCase))
                    items.Add(new CompletionItem(value, CompletionKind.UnityName, null, category, category));
                if (kind == UnityStringKind.Scene)
                {
                    foreach (var path in snapshot.ScenePaths)
                        items.Add(new CompletionItem(path, CompletionKind.UnityName, null, category, category));
                }
                return new UnityStringCompletionResult { Kind = kind, Items = items, ContentStart = literal.Token.SpanStart + 1 };
            });
        }

        /// <summary>
        /// Members that can be overridden when the caret follows "override"; null otherwise. The returned start is
        /// where the accepted stub replaces the typed text (the member's first modifier).
        /// </summary>
        public Task<(List<CompletionItem> items, int replaceStart)> GetOverrideCompletionsAsync(string code, int caretPosition)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                if (state == null) return ((List<CompletionItem>)null, -1);
                var syntaxTree = state.Tree.WithChangedText(Microsoft.CodeAnalysis.Text.SourceText.From(code ?? string.Empty));
                SemanticModel model;
                try { model = state.Compilation.ReplaceSyntaxTree(state.Tree, syntaxTree).GetSemanticModel(syntaxTree); }
                catch (ArgumentException) { return ((List<CompletionItem>)null, -1); }

                var candidates = OverrideCompletion.GetCandidates(syntaxTree.GetRoot(), model, caretPosition, out int replaceStart);
                if (candidates == null) return ((List<CompletionItem>)null, -1);
                var items = candidates.Select(c => new CompletionItem(c.Name, CompletionKind.Method, null, "override", c.Signature, c.Snippet)).ToList();
                return (items, replaceStart);
            });
        }

        public Task<List<CompletionItem>> GetScopeCompletionsAsync(string code, int caretPosition)
        {
            return Task.Run(() =>
            {
                var completions = new List<CompletionItem>();
                var state = _currentState;
                if (state == null) return completions;

                var newText = Microsoft.CodeAnalysis.Text.SourceText.From(code ?? string.Empty);
                var syntaxTree = state.Tree.WithChangedText(newText);
                var compilation = state.Compilation.ReplaceSyntaxTree(state.Tree, syntaxTree);
                var semanticModel = compilation.GetSemanticModel(syntaxTree);
                if (semanticModel == null) return completions;

                var root = syntaxTree.GetRoot();
                if (caretPosition < 0 || caretPosition > root.FullSpan.End) return completions;

                var existingTypes = new HashSet<string>();

                // Lookup symbols accessible at this exact position
                var symbols = semanticModel.LookupSymbols(caretPosition);
                foreach (var symbol in symbols)
                {
                    if (symbol.Kind == SymbolKind.Local || symbol.Kind == SymbolKind.Parameter ||
                        symbol.Kind == SymbolKind.Field || symbol.Kind == SymbolKind.Property ||
                        symbol.Kind == SymbolKind.Method || symbol.Kind == SymbolKind.Event ||
                        symbol.Kind == SymbolKind.NamedType)
                    {
                        if (!string.IsNullOrEmpty(symbol.Name) && !symbol.Name.Contains("<") && !symbol.Name.Contains(">"))
                        {
                            if (symbol.GetAttributes().Any(ad => ad.AttributeClass?.Name == "ObsoleteAttribute" || ad.AttributeClass?.Name == "Obsolete")) continue;
                            
                            string sig = symbol.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                            completions.Add(new CompletionItem(symbol.Name, MapSymbolKind(symbol), null, null, sig));

                            if (symbol.Kind == SymbolKind.NamedType) existingTypes.Add(symbol.Name);
                        }
                    }
                }

                BuildUnimportedTypesCache(compilation);
                if (_unimportedTypesCache != null)
                {
                    foreach (var kvp in _unimportedTypesCache)
                    {
                        if (!existingTypes.Contains(kvp.Key))
                        {
                            completions.Add(new CompletionItem(kvp.Key, CompletionKind.Class, kvp.Value));
                        }
                    }
                }

                // Snippets: built-ins, Unity messages with their real signatures and the user's snippets.json
                foreach (var snippet in SnippetLibrary.All())
                {
                    string preview = SnippetParser.Expand(snippet.Body).Text.Split('\n')[0];
                    completions.Add(new CompletionItem(snippet.Prefix, CompletionKind.Snippet, null, snippet.Description, preview, snippet.Body));
                }

                // Add C# keywords
                foreach (var kw in CSHARP_KEYWORDS) completions.Add(new CompletionItem(kw, CompletionKind.Keyword));

                return completions.GroupBy(x => x.Name).Select(g => g.OrderByDescending(c => c.Kind == CompletionKind.Snippet ? 1 : 0).First()).OrderByDescending(x => GetCompletionPriority(x)).ThenBy(x => x.Name).ToList();
            });
        }

        /// <summary>
        /// Extracts syntax highlighting spans asynchronously using Roslyn's syntax tree.
        /// </summary>
        public Task<List<SyntaxSpan>> GetSyntaxHighlightsAsync(CancellationToken cancellationToken = default)
        {
            var theme = CodeIDESettings.Current.Theme;
            bool semantic = CodeIDESettings.Current.SmartCode.SemanticHighlighting;
            string Hex(Color c) => "#" + ColorUtility.ToHtmlStringRGBA(c);
            string keyword = Hex(theme.KeywordColor), str = Hex(theme.StringColor), comment = Hex(theme.CommentColor);
            string type = Hex(theme.TypeColor), method = Hex(theme.MethodColor), variable = Hex(theme.VariableColor);
            string number = Hex(theme.NumberColor), field = Hex(theme.FieldColor), property = Hex(theme.PropertyColor);
            string parameter = Hex(theme.ParameterColor), unityMessage = Hex(theme.UnityMessageColor), preprocessor = Hex(theme.InlayHintColor);

            return Task.Run(() =>
            {
                var spans = new List<SyntaxSpan>();
                var state = _currentState;
                if (state == null) return spans;

                foreach (var c in CodeClassifier.Classify(state.Tree.GetRoot(cancellationToken), state.Model, cancellationToken))
                {
                    switch (c.Class)
                    {
                        case TokenClass.Keyword: spans.Add(new SyntaxSpan(c.Start, c.Length, keyword, isBold: true)); break;
                        case TokenClass.String: spans.Add(new SyntaxSpan(c.Start, c.Length, str)); break;
                        case TokenClass.Comment: spans.Add(new SyntaxSpan(c.Start, c.Length, comment, isItalic: true)); break;
                        case TokenClass.Preprocessor: spans.Add(new SyntaxSpan(c.Start, c.Length, preprocessor)); break;
                        case TokenClass.Type: spans.Add(new SyntaxSpan(c.Start, c.Length, type)); break;
                        case TokenClass.Method:
                        case TokenClass.Event:
                            spans.Add(new SyntaxSpan(c.Start, c.Length, method)); break;
                        case TokenClass.UnityMessage:
                            if (semantic) spans.Add(new SyntaxSpan(c.Start, c.Length, unityMessage, isBold: true));
                            else spans.Add(new SyntaxSpan(c.Start, c.Length, method));
                            break;
                        case TokenClass.Number: if (semantic) spans.Add(new SyntaxSpan(c.Start, c.Length, number)); break;
                        case TokenClass.Field:
                        case TokenClass.EnumMember:
                            spans.Add(new SyntaxSpan(c.Start, c.Length, semantic ? field : variable)); break;
                        case TokenClass.Property: spans.Add(new SyntaxSpan(c.Start, c.Length, semantic ? property : variable)); break;
                        case TokenClass.Parameter:
                            if (semantic) spans.Add(new SyntaxSpan(c.Start, c.Length, parameter, isItalic: true));
                            else spans.Add(new SyntaxSpan(c.Start, c.Length, variable));
                            break;
                        case TokenClass.Local: spans.Add(new SyntaxSpan(c.Start, c.Length, variable)); break;
                    }
                }
                return spans;
            });
        }

