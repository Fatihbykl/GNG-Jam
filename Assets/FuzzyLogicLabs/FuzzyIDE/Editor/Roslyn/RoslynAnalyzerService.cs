        public Task<SmartInjectionInfo> GetSmartInjectionPointsAsync(int caretPosition, string code)
        {
            return Task.Run(() =>
            {
                var result = new SmartInjectionInfo { IsValid = false };
                var syntaxTree = CSharpSyntaxTree.ParseText(code ?? string.Empty);
                var root = syntaxTree.GetRoot();

                if (caretPosition < 0 || caretPosition > root.FullSpan.End) return result;

                var token = root.FindToken(caretPosition);
                var classDeclaration = token.Parent?.AncestorsAndSelf().OfType<ClassDeclarationSyntax>().FirstOrDefault();

                if (classDeclaration == null) return result;

                result.IsValid = true;
                result.ClassName = classDeclaration.Identifier.Text;

                // Get line number for class opening brace
                var classLineSpan = syntaxTree.GetText().Lines;
                result.ClassDeclarationStartLine = classLineSpan.GetLineFromPosition(classDeclaration.SpanStart).LineNumber;
                result.ClassBodyStartLine = classLineSpan.GetLineFromPosition(classDeclaration.OpenBraceToken.SpanStart).LineNumber;
                result.ClassBodyEndLine = classLineSpan.GetLineFromPosition(classDeclaration.CloseBraceToken.SpanStart).LineNumber;

                var awakeMethod = classDeclaration.Members.OfType<MethodDeclarationSyntax>()
                    .FirstOrDefault(m => m.Identifier.Text == "Awake" && m.ParameterList.Parameters.Count == 0);

