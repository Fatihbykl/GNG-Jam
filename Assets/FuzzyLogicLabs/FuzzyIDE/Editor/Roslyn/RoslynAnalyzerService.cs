                {
                    result.HasAwake = true;
                    result.AwakeBodyStartLine = classLineSpan.GetLineFromPosition(awakeMethod.Body.OpenBraceToken.SpanStart).LineNumber;
                }
                else
                {
                    result.HasAwake = false;
                    result.AwakeBodyStartLine = -1;
                }

                return result;
            });
        }

        public class SmartDragDropResult
        {
            public bool IsValid;
            public string NewFullCode;
            public string UniqueVariableName;
            public int OldClassStartLine;
            public int OldClassStartCol;
            public int OldClassEndLine;
            public int OldClassEndCol;
            public string NewClassCode;
        }

        public Task<SmartDragDropResult> ProcessSmartDragDropInjectionAsync(string fullCode, int caretPosition, bool isLocal, string objType, string baseVarName)
        {
            return Task.Run(() =>
            {
                var result = new SmartDragDropResult { IsValid = false };
                var syntaxTree = CSharpSyntaxTree.ParseText(fullCode ?? string.Empty);
                var root = syntaxTree.GetRoot();

                if (caretPosition < 0 || caretPosition > root.FullSpan.End) return result;

                var token = root.FindToken(caretPosition);
                var oldClass = token.Parent?.AncestorsAndSelf().OfType<ClassDeclarationSyntax>().FirstOrDefault();

                if (oldClass == null) return result;

                var existingNames = new System.Collections.Generic.HashSet<string>();
                foreach (var member in oldClass.Members)
                {
                    if (member is FieldDeclarationSyntax fd)
                    {
                        foreach (var v in fd.Declaration.Variables) existingNames.Add(v.Identifier.Text);
                    }
                    else if (member is PropertyDeclarationSyntax pd)
                    {
                        existingNames.Add(pd.Identifier.Text);
                    }
                    else if (member is MethodDeclarationSyntax md)
                    {
                        existingNames.Add(md.Identifier.Text);
                    }
                }

                string uniqueVarName = baseVarName;
                int counter = 1;
                while (existingNames.Contains(uniqueVarName))
                {
                    uniqueVarName = baseVarName + counter.ToString();
                    counter++;
                }

                ClassDeclarationSyntax newClass = oldClass;

                if (isLocal)
                {
                    var fieldDecl = SyntaxFactory.FieldDeclaration(
                        SyntaxFactory.VariableDeclaration(SyntaxFactory.IdentifierName(objType))
                        .WithVariables(SyntaxFactory.SingletonSeparatedList(SyntaxFactory.VariableDeclarator(uniqueVarName))))
                        .WithModifiers(SyntaxFactory.TokenList(SyntaxFactory.Token(SyntaxKind.PrivateKeyword)));

                    var awakeMethod = newClass.Members.OfType<MethodDeclarationSyntax>()
                        .FirstOrDefault(m => m.Identifier.Text == "Awake" && m.ParameterList.Parameters.Count == 0);

                    var assignExpr = SyntaxFactory.ExpressionStatement(
                        SyntaxFactory.AssignmentExpression(
                            SyntaxKind.SimpleAssignmentExpression,
                            SyntaxFactory.IdentifierName(uniqueVarName),
                            SyntaxFactory.InvocationExpression(
                                SyntaxFactory.GenericName(SyntaxFactory.Identifier("GetComponent"))
                                .WithTypeArgumentList(SyntaxFactory.TypeArgumentList(SyntaxFactory.SingletonSeparatedList<TypeSyntax>(SyntaxFactory.IdentifierName(objType))))
                            )
                        )
                    );

                    if (awakeMethod != null && awakeMethod.Body != null)
                    {
                        var newAwake = awakeMethod.WithBody(awakeMethod.Body.AddStatements(assignExpr));
                        newClass = newClass.ReplaceNode(awakeMethod, newAwake);
                        newClass = newClass.WithMembers(newClass.Members.Insert(0, fieldDecl));
                    }
                    else
                    {
                        var newAwake = SyntaxFactory.MethodDeclaration(SyntaxFactory.PredefinedType(SyntaxFactory.Token(SyntaxKind.VoidKeyword)), "Awake")
                            .WithModifiers(SyntaxFactory.TokenList(SyntaxFactory.Token(SyntaxKind.PrivateKeyword)))
                            .WithBody(SyntaxFactory.Block(assignExpr));

                        newClass = newClass.WithMembers(newClass.Members.Insert(0, fieldDecl));
                        newClass = newClass.AddMembers(newAwake);
                    }
                }
                else
                {
                    var attrList = SyntaxFactory.AttributeList(SyntaxFactory.SingletonSeparatedList(
                        SyntaxFactory.Attribute(SyntaxFactory.IdentifierName("SerializeField"))
                    ));

                    var fieldDecl = SyntaxFactory.FieldDeclaration(
                        SyntaxFactory.VariableDeclaration(SyntaxFactory.IdentifierName(objType))
                        .WithVariables(SyntaxFactory.SingletonSeparatedList(SyntaxFactory.VariableDeclarator(uniqueVarName))))
                        .WithAttributeLists(SyntaxFactory.SingletonList(attrList))
                        .WithModifiers(SyntaxFactory.TokenList(SyntaxFactory.Token(SyntaxKind.PrivateKeyword)));

                    newClass = newClass.WithMembers(newClass.Members.Insert(0, fieldDecl));
                }

                newClass = newClass.WithAdditionalAnnotations(Microsoft.CodeAnalysis.Formatting.Formatter.Annotation);
                var newRoot = root.ReplaceNode(oldClass, newClass);

                try
                {
                    var assemblies = new System.Reflection.Assembly[]
                    {
                        typeof(Microsoft.CodeAnalysis.Workspace).Assembly,
                        typeof(Microsoft.CodeAnalysis.CSharp.Formatting.CSharpFormattingOptions).Assembly
                    };

                    var hostServices = Microsoft.CodeAnalysis.Host.Mef.MefHostServices.Create(assemblies);
                    using (var workspace = new Microsoft.CodeAnalysis.AdhocWorkspace(hostServices))
                    {
                        var formattedRoot = Microsoft.CodeAnalysis.Formatting.Formatter.Format(newRoot, workspace);
                        var formattedClass = formattedRoot.GetAnnotatedNodes(Microsoft.CodeAnalysis.Formatting.Formatter.Annotation).FirstOrDefault() as ClassDeclarationSyntax;

                        if (formattedClass != null)
                        {
                            newRoot = formattedRoot;
                            newClass = formattedClass;
                        }
                    }
                }
                catch (Exception)
                {
                    // Fallback handled by using newRoot / newClass as is
                    newClass = newClass.NormalizeWhitespace();
                }

                var classLineSpan = syntaxTree.GetText().Lines;
                var startLinePos = classLineSpan.GetLinePosition(oldClass.FullSpan.Start);
                var endLinePos = classLineSpan.GetLinePosition(oldClass.FullSpan.End);

                result.IsValid = true;
                result.UniqueVariableName = uniqueVarName;
                result.OldClassStartLine = startLinePos.Line;
                result.OldClassStartCol = startLinePos.Character;
                result.OldClassEndLine = endLinePos.Line;
                result.OldClassEndCol = endLinePos.Character;
                result.NewClassCode = newClass.ToFullString();
                result.NewFullCode = newRoot.ToFullString();

                return result;
            });
        }

        public Task<string> FormatDocumentAsync(string code)
        {
            return Task.Run(() =>
            {
                try
                {
                    var syntaxTree = CSharpSyntaxTree.ParseText(code);
                    var root = EnsureNewlinesAfterSemicolons(syntaxTree.GetRoot());

                    var assemblies = new System.Reflection.Assembly[]
                    {
                        typeof(Microsoft.CodeAnalysis.Workspace).Assembly,
                        typeof(Microsoft.CodeAnalysis.CSharp.Formatting.CSharpFormattingOptions).Assembly
                    };

                    var hostServices = Microsoft.CodeAnalysis.Host.Mef.MefHostServices.Create(assemblies);
                    using (var workspace = new Microsoft.CodeAnalysis.AdhocWorkspace(hostServices))
                    {
                        var formattedRoot = Microsoft.CodeAnalysis.Formatting.Formatter.Format(root, workspace);
                        return formattedRoot.ToFullString();
                    }
                }
                catch (Exception e)
                {
                    if (e is System.Reflection.ReflectionTypeLoadException)
                    {
                        UnityEngine.Debug.LogWarning("[FuzzyIDE] Workspaces SQLite dependency missing. Falling back to NormalizeWhitespace(). To get perfect formatting, please add 'SQLitePCLRaw.core.dll' to your project.");
                        var syntaxTree = CSharpSyntaxTree.ParseText(code);
                        var root = EnsureNewlinesAfterSemicolons(syntaxTree.GetRoot());
                        return root.NormalizeWhitespace().ToFullString();
                    }
                    UnityEngine.Debug.LogError($"[FuzzyIDE] Formatting failed: {e.Message}");
                    return code;
                }
            });
        }

        private static SyntaxNode EnsureNewlinesAfterSemicolons(SyntaxNode root)
        {
            if (root == null) return root;

            var tokensToReplace = new List<(SyntaxToken oldToken, SyntaxToken newToken)>();

            foreach (var token in root.DescendantTokens())
            {
                if (token.IsKind(SyntaxKind.SemicolonToken))
                {
                    // Skip semicolons in for-loop header clauses: for (int i = 0; i < 10; i++)
                    if (token.Parent is ForStatementSyntax forStmt)
                    {
                        if (token == forStmt.FirstSemicolonToken || token == forStmt.SecondSemicolonToken)
                        {
                            continue;
                        }
                    }

                    // Skip auto-property accessor semicolons: get; set;
                    if (token.Parent is AccessorDeclarationSyntax)
                    {
                        continue;
                    }

                    var nextToken = token.GetNextToken();
                    if (nextToken.IsKind(SyntaxKind.None) || nextToken.IsKind(SyntaxKind.EndOfFileToken))
                    {
                        continue;
                    }

                    var tokenSpan = token.GetLocation().GetLineSpan();
                    var nextSpan = nextToken.GetLocation().GetLineSpan();

                    if (tokenSpan.EndLinePosition.Line == nextSpan.StartLinePosition.Line)
                    {
                        var trailingTrivia = token.TrailingTrivia;
                        bool hasNewline = false;
                        foreach (var trivia in trailingTrivia)
                        {
                            if (trivia.IsKind(SyntaxKind.EndOfLineTrivia))
                            {
                                hasNewline = true;
                                break;
                            }
                        }

                        if (!hasNewline)
                        {
                            var newTrailing = trailingTrivia.Add(SyntaxFactory.CarriageReturnLineFeed);
                            var newToken = token.WithTrailingTrivia(newTrailing);
                            tokensToReplace.Add((token, newToken));
                        }
                    }
                }
            }

            if (tokensToReplace.Count > 0)
            {
                var dict = new Dictionary<SyntaxToken, SyntaxToken>();
                foreach (var item in tokensToReplace)
                {
                    dict[item.oldToken] = item.newToken;
                }

                root = root.ReplaceTokens(
                    dict.Keys,
                    (oldTok, _) => dict.TryGetValue(oldTok, out var newTok) ? newTok : oldTok
                );
            }

            return root;
        }

        public Task<List<QuickAction>> GetQuickActionsAsync(string code, int caretPosition)
        {
            return Task.Run(async () =>
            {
                var actions = new List<QuickAction>();
                var state = _currentState;
                if (state == null) return actions;

                var newText = Microsoft.CodeAnalysis.Text.SourceText.From(code ?? string.Empty);
                var syntaxTree = state.Tree.WithChangedText(newText);
                var compilation = state.Compilation.ReplaceSyntaxTree(state.Tree, syntaxTree);
                var semanticModel = compilation.GetSemanticModel(syntaxTree);
                if (semanticModel == null) return actions;
                var root = syntaxTree.GetRoot();

                // Unity analyzer fixes for the issue under the caret come first.
                foreach (var issue in UnityAnalyzers.Analyze(root, semanticModel))
                {
                    if (caretPosition < issue.Span.Start || caretPosition > issue.Span.End) continue;
                    foreach (var fix in issue.Fixes)
                        actions.Add(new QuickAction { Title = fix.Title, NewCode = fix.Apply(newText) });
                }

                // Get diagnostics touching the caret
                var diagnostics = semanticModel.GetDiagnostics(new Microsoft.CodeAnalysis.Text.TextSpan(caretPosition, 0));
                var token = root.FindToken(caretPosition);
                var node = token.Parent;

                // 0. Missing Namespace (CS0246 / CS0103)
                foreach (var diag in diagnostics.Where(d => d.Id == "CS0246" || d.Id == "CS0103"))
                {
                    var errorNode = root.FindNode(diag.Location.SourceSpan);
                    if (errorNode is IdentifierNameSyntax idNode)
                    {
                        string missingType = idNode.Identifier.Text;
                        var namespaces = await GetPossibleNamespacesAsync(missingType);
                        foreach (var ns in namespaces)
                        {
                            string newCodeStr = await AddUsingDirectiveAsync(code, ns);
                            if (!string.IsNullOrEmpty(newCodeStr) && newCodeStr != code)
                            {
                                actions.Add(new QuickAction { Title = $"Using {ns}", NewCode = newCodeStr });
                            }
                        }
                    }
                }

                // 1. Missing Methods (CS0103)
                foreach (var diag in diagnostics.Where(d => d.Id == "CS0103"))
                {
                    var errorNode = root.FindNode(diag.Location.SourceSpan);
                    if (errorNode is IdentifierNameSyntax idNode && idNode.Parent is InvocationExpressionSyntax invocation)
                    {
                        var classDecl = errorNode.AncestorsAndSelf().OfType<ClassDeclarationSyntax>().FirstOrDefault();
                        if (classDecl != null)
                        {
                            string methodName = idNode.Identifier.Text;
                            
                            // Check arguments to generate parameters
                            var args = invocation.ArgumentList.Arguments;
                            var paramList = new List<string>();
                            for(int i = 0; i < args.Count; i++)
                            {
                                var argType = semanticModel.GetTypeInfo(args[i].Expression).Type;
                                string typeName = argType != null && argType.TypeKind != TypeKind.Error ? argType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat) : "object";
                                paramList.Add($"{typeName} arg{i+1}");
                            }
                            
                            string paramsStr = string.Join(", ", paramList);
                            string stub = $"\n    private void {methodName}({paramsStr})\n    {{\n        throw new System.NotImplementedException();\n    }}\n";

                            var closeBraceToken = classDecl.CloseBraceToken;
                            var newRoot = root.InsertNodesBefore(closeBraceToken.Parent.ChildNodes().LastOrDefault() ?? closeBraceToken.Parent, new[] { SyntaxFactory.ParseMemberDeclaration(stub) });

                            actions.Add(new QuickAction { Title = $"Generate method '{methodName}'", NewCode = newRoot.ToFullString() });
                        }
                    }
                }

                // 2. Implement Interface (CS0535)
                foreach (var diag in diagnostics.Where(d => d.Id == "CS0535"))
                {
                    var classDecl = root.FindNode(diag.Location.SourceSpan).AncestorsAndSelf().OfType<ClassDeclarationSyntax>().FirstOrDefault();
                    if (classDecl != null && classDecl.BaseList != null)
                    {
                        var classSymbol = semanticModel.GetDeclaredSymbol(classDecl) as INamedTypeSymbol;
                        if (classSymbol != null)
                        {
                            var missingMembers = new List<(string Name, string Stub)>();
                            foreach (var iface in classSymbol.AllInterfaces)
                            {
                                foreach (var member in iface.GetMembers())
                                {
                                    var implementation = classSymbol.FindImplementationForInterfaceMember(member);
                                    if (implementation == null)
                                    {
                                        if (member is IMethodSymbol methodSymbol)
                                        {
                                            string returnType = methodSymbol.ReturnType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                                            var pList = methodSymbol.Parameters.Select(p => $"{p.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)} {p.Name}");
                                            string pStr = string.Join(", ", pList);
                                            missingMembers.Add((methodSymbol.Name, $"\n    public {returnType} {methodSymbol.Name}({pStr})\n    {{\n        throw new System.NotImplementedException();\n    }}\n"));
                                        }
                                        else if (member is IPropertySymbol propSymbol)
                                        {
                                            string returnType = propSymbol.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                                            string accessors = propSymbol.IsReadOnly ? "get;" : "get; set;";
                                            missingMembers.Add((propSymbol.Name, $"\n    public {returnType} {propSymbol.Name} {{ {accessors} }}\n"));
                                        }
                                    }
                                }
                            }
                            
                            if (missingMembers.Count > 0)
                            {
                                string allStubs = string.Join("", missingMembers.Select(m => m.Stub));
                                var allMembers = SyntaxFactory.ParseMemberDeclaration("class Temp {\n" + allStubs + "\n}");
                                var allClassMembers = ((ClassDeclarationSyntax)allMembers).Members;
                                
                                var allNewClass = classDecl.AddMembers(allClassMembers.ToArray());
                                var allNewRoot = root.ReplaceNode(classDecl, allNewClass);
                                
                                var mainQa = new QuickAction { Title = missingMembers.Count > 1 ? "Implement interface members..." : "Implement interface member", NewCode = allNewRoot.ToFullString() };
                                
                                if (missingMembers.Count > 1)
                                {
                                    mainQa.SubActions.Add(new QuickAction { Title = "Implement all members", NewCode = allNewRoot.ToFullString() });
                                    foreach (var member in missingMembers)
                                    {
                                        var singleMembers = SyntaxFactory.ParseMemberDeclaration("class Temp {\n" + member.Stub + "\n}");
                                        var singleClassMembers = ((ClassDeclarationSyntax)singleMembers).Members;
                                        var singleNewClass = classDecl.AddMembers(singleClassMembers.ToArray());
                                        var singleNewRoot = root.ReplaceNode(classDecl, singleNewClass);
                                        
                                        mainQa.SubActions.Add(new QuickAction { Title = $"Implement {member.Name}", NewCode = singleNewRoot.ToFullString() });
                                    }
                                }
                                
                                // To avoid adding identical QuickActions if there are multiple CS0535 diagnostics for the same class
                                if (!actions.Any(a => a.Title == mainQa.Title))
                                {
                                    actions.Add(mainQa);
                                }
                            }
                        }
                    }
                }


                // 4. Add [SerializeField]
                var fieldDecl = node.AncestorsAndSelf().OfType<FieldDeclarationSyntax>().FirstOrDefault();
                if (fieldDecl != null)
                {
                    bool isPublic = fieldDecl.Modifiers.Any(SyntaxKind.PublicKeyword);
                    bool hasSerializeField = fieldDecl.AttributeLists.ToString().Contains("SerializeField");
                    
                    if (!isPublic && !hasSerializeField)
                    {
                        var attr = SyntaxFactory.AttributeList(SyntaxFactory.SingletonSeparatedList(SyntaxFactory.Attribute(SyntaxFactory.IdentifierName("SerializeField")))).NormalizeWhitespace();
                        var newField = fieldDecl.AddAttributeLists(attr).WithLeadingTrivia(fieldDecl.GetLeadingTrivia());
                        
                        // We must remove leading trivia from the original field's first token, otherwise the attribute gets pushed down strangely.
                        var firstTokenAfterAttr = newField.Modifiers.Any() 
                            ? newField.Modifiers.First() 
                            : newField.Declaration.Type.GetFirstToken();
                        
                        if (firstTokenAfterAttr.Kind() != SyntaxKind.None)
                        {
                            newField = newField.ReplaceToken(firstTokenAfterAttr, firstTokenAfterAttr.WithLeadingTrivia(SyntaxFactory.Space));
                        }
                        
                        var newRoot = root.ReplaceNode(fieldDecl, newField);
                        actions.Add(new QuickAction { Title = "Add [SerializeField]", NewCode = newRoot.ToFullString() });
                    }
                }

                // 5. Remove Unused Usings (CS8019)
                // Usings are usually at the top of the file, we can just check all CS8019 in the file.
                var allDiags = semanticModel.GetDiagnostics();
                var unusedUsings = allDiags.Where(d => d.Id == "CS8019").ToList();
                if (unusedUsings.Count > 0)
                {
                    var nodesToRemove = unusedUsings.Select(d => root.FindNode(d.Location.SourceSpan).AncestorsAndSelf().OfType<UsingDirectiveSyntax>().FirstOrDefault()).Where(n => n != null).ToList();
                    if (nodesToRemove.Count > 0)
                    {
                        var newRoot = root.RemoveNodes(nodesToRemove, SyntaxRemoveOptions.KeepNoTrivia);
                        actions.Add(new QuickAction { Title = "Remove unused usings", NewCode = newRoot.ToFullString() });
                    }
                }

                return actions;
            });
        }

        public Task<List<string>> GetPossibleNamespacesAsync(string unresolvedType)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                if (state == null) return new List<string>();

                var namespaces = new HashSet<string>();

                foreach (var reference in state.Compilation.References)
                {
                    var symbol = state.Compilation.GetAssemblyOrModuleSymbol(reference) as IAssemblySymbol;
                    if (symbol != null)
                    {
                        FindTypeInNamespace(symbol.GlobalNamespace, unresolvedType, namespaces);
                    }
                }

                FindTypeInNamespace(state.Compilation.GlobalNamespace, unresolvedType, namespaces);

                return namespaces.ToList();
            });
        }

        private void FindTypeInNamespace(INamespaceSymbol ns, string typeName, HashSet<string> results)
        {
            if (ns == null) return;

            foreach (var type in ns.GetTypeMembers())
            {
                if (type.Name == typeName)
                {
                    string nsString = ns.ToDisplayString();
                    if (!string.IsNullOrEmpty(nsString) && nsString != "<global namespace>")
                    {
                        results.Add(nsString);
                    }
                }
            }

            foreach (var childNs in ns.GetNamespaceMembers())
            {
                FindTypeInNamespace(childNs, typeName, results);
            }
        }

        public Task<string> AddUsingDirectiveAsync(string code, string namespaceName)
        {
            return Task.Run(() =>
            {
                try
                {
                    var syntaxTree = CSharpSyntaxTree.ParseText(code);
                    var root = syntaxTree.GetRoot() as CompilationUnitSyntax;
                    if (root == null) return code;

                    bool exists = root.Usings.Any(u => u.Name.ToString() == namespaceName);
                    if (exists) return code;

                    var newUsing = SyntaxFactory.UsingDirective(SyntaxFactory.ParseName(namespaceName))
                        .NormalizeWhitespace()
                        .WithTrailingTrivia(SyntaxFactory.CarriageReturnLineFeed);

                    var newRoot = root.AddUsings(newUsing);
                    newRoot = newRoot.WithAdditionalAnnotations(Microsoft.CodeAnalysis.Formatting.Formatter.Annotation);

                    var assemblies = new System.Reflection.Assembly[]
                    {
                        typeof(Microsoft.CodeAnalysis.Workspace).Assembly,
                        typeof(Microsoft.CodeAnalysis.CSharp.Formatting.CSharpFormattingOptions).Assembly
                    };

                    var hostServices = Microsoft.CodeAnalysis.Host.Mef.MefHostServices.Create(assemblies);
                    using (var workspace = new Microsoft.CodeAnalysis.AdhocWorkspace(hostServices))
                    {
                        var formattedRoot = Microsoft.CodeAnalysis.Formatting.Formatter.Format(newRoot, workspace);
                        return formattedRoot.ToFullString();
                    }
                }
                catch (Exception e)
                {
                    if (e is System.Reflection.ReflectionTypeLoadException)
                    {
                        var syntaxTree = CSharpSyntaxTree.ParseText(code);
                        var root = syntaxTree.GetRoot() as CompilationUnitSyntax;
                        var newUsing = SyntaxFactory.UsingDirective(SyntaxFactory.ParseName(namespaceName))
                            .NormalizeWhitespace()
                            .WithTrailingTrivia(SyntaxFactory.CarriageReturnLineFeed);
                        return root.AddUsings(newUsing).ToFullString();
                    }
                    UnityEngine.Debug.LogError($"[FuzzyIDE] Adding using failed: {e.Message}");
                    return code;
                }
            });
        }

        public Task<List<FoldableBlock>> GetFoldableBlocksAsync()
        {
            return Task.Run(() =>
            {
                var blocks = new List<FoldableBlock>();
                var state = _currentState;
                if (state == null) return blocks;

                var root = state.Tree.GetRoot();
                var lines = state.Tree.GetText().Lines;

                // Add syntax blocks (Classes, Methods, Namespaces, Structs, Enums)
                var foldableNodes = root.DescendantNodes().Where(n => 
                    n is ClassDeclarationSyntax || 
                    n is MethodDeclarationSyntax || 
                    n is StructDeclarationSyntax || 
                    n is EnumDeclarationSyntax || 
                    n is NamespaceDeclarationSyntax || 
                    n is PropertyDeclarationSyntax);

                foreach (var node in foldableNodes)
                {
                    int startLine = lines.GetLineFromPosition(node.SpanStart).LineNumber;
                    int endLine = lines.GetLineFromPosition(node.Span.End).LineNumber;
                    if (endLine > startLine)
                    {
                        blocks.Add(new FoldableBlock(startLine, endLine, false));
                    }
                }

                // Add regions
                var regions = root.DescendantTrivia().Where(t => t.IsKind(SyntaxKind.RegionDirectiveTrivia)).Select(t => t.GetStructure()).OfType<RegionDirectiveTriviaSyntax>();
                foreach (var region in regions)
                {
                    var endRegions = region.GetRelatedDirectives().OfType<EndRegionDirectiveTriviaSyntax>().FirstOrDefault();
                    if (endRegions != null)
                    {
                        int startLine = lines.GetLineFromPosition(region.SpanStart).LineNumber;
                        int endLine = lines.GetLineFromPosition(endRegions.Span.End).LineNumber;
                        if (endLine > startLine)
                        {
                            blocks.Add(new FoldableBlock(startLine, endLine, false));
                        }
                    }
                }

                // Sort by start line, then descending by end line to ensure nested blocks are handled properly
                return blocks.OrderBy(b => b.StartLine).ThenByDescending(b => b.EndLine).ToList();
            });
        }

        public Task<HoverInfoResult> GetHoverInfoAsync(string code, int position)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                if (state == null || string.IsNullOrEmpty(code)) return null;

                var newText = Microsoft.CodeAnalysis.Text.SourceText.From(code);
                var syntaxTree = state.Tree.WithChangedText(newText);
                var compilation = state.Compilation.ReplaceSyntaxTree(state.Tree, syntaxTree);
                var semanticModel = compilation.GetSemanticModel(syntaxTree);
                if (semanticModel == null) return null;

                var root = syntaxTree.GetRoot();
                if (position < 0 || position >= root.FullSpan.End) return null;

                var token = root.FindToken(position);
                var node = token.Parent;
                if (node == null) return null;

                var symbolInfo = semanticModel.GetSymbolInfo(node);
                var symbol = symbolInfo.Symbol ?? symbolInfo.CandidateSymbols.FirstOrDefault();
                var typeInfo = semanticModel.GetTypeInfo(node);

                string symbolName = null;
                string displayString = null;
                string docComment = null;
                string category = null;
                string locationInfo = null;
                string liveValue = null;

                if (symbol != null)
                {
                    symbolName = symbol.Name;
                    displayString = symbol.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                    docComment = ExtractSummary(symbol.GetDocumentationCommentXml());
                    category = symbol.Kind.ToString();
                    if (symbol.ContainingType != null)
                    {
                        locationInfo = symbol.ContainingType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                    }
                    else if (symbol.ContainingNamespace != null && !symbol.ContainingNamespace.IsGlobalNamespace)
                    {
                        locationInfo = symbol.ContainingNamespace.ToDisplayString();
                    }
                }
                else if (typeInfo.Type != null && typeInfo.Type.Kind != SymbolKind.ErrorType)
                {
                    symbolName = typeInfo.Type.Name;
                    displayString = typeInfo.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat);
                    docComment = ExtractSummary(typeInfo.Type.GetDocumentationCommentXml());
                    category = "Type";
                    if (typeInfo.Type.ContainingNamespace != null && !typeInfo.Type.ContainingNamespace.IsGlobalNamespace)
                    {
                        locationInfo = typeInfo.Type.ContainingNamespace.ToDisplayString();
                    }
                }

                if (string.IsNullOrEmpty(displayString)) return null;

                if (!string.IsNullOrEmpty(symbolName))
                {
                    try
                    {
                        foreach (var asm in UnityCompat.GetLoadedAssemblies())
                        {
                            var trackerType = asm.GetType("FuzzyLogicLabs.LiveStateTracker");
                            if (trackerType != null)
                            {
                                var stateField = trackerType.GetField("State", System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static);
                                if (stateField?.GetValue(null) is System.Collections.IDictionary dict)
                                {
                                    foreach (System.Collections.DictionaryEntry kvp in dict)
                                    {
                                        object val = kvp.Value;
                                        if (val != null)
                                        {
                                            var varNameField = val.GetType().GetField("VariableName");
                                            if (varNameField?.GetValue(val) is string vName && vName == symbolName)
                                            {
                                                var curValField = val.GetType().GetField("CurrentValue");
                                                liveValue = curValField?.GetValue(val) as string;
                                                break;
                                            }
                                        }
                                    }
                                }
                                break;
                            }
                        }
                    }
                    catch { }
                }

                return new HoverInfoResult
                {
                    SymbolName = symbolName,
                    DisplayString = displayString,
                    Documentation = docComment,
                    Category = category,
                    LocationInfo = locationInfo,
                    LiveValue = liveValue
                };
            });
        }
    }

    public class HoverInfoResult
    {
        public string SymbolName;
        public string DisplayString;
        public string Documentation;
        public string Category;
        public string LocationInfo;
        public string LiveValue;
    }
