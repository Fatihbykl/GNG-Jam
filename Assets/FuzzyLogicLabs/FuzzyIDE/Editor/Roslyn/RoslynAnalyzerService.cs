        private static readonly System.Text.RegularExpressions.Regex s_CannotConvertRegex = new System.Text.RegularExpressions.Regex(
            @"[Cc]annot.*?convert\s+(?:(?:type|from)\s+)*'(?<from>[^']+)'\s+to\s+'(?<to>[^']+)'",
            System.Text.RegularExpressions.RegexOptions.Compiled | System.Text.RegularExpressions.RegexOptions.IgnoreCase);

        private static readonly System.Text.RegularExpressions.Regex s_OperatorDuplicateTypeRegex = new System.Text.RegularExpressions.Regex(
            @"[Oo]perator\s+'(?<op>[^']+)'\s+(?:cannot\s+be\s+applied\s+to|is\s+ambiguous\s+on)\s+operands\s+of\s+type\s+'(?<from>[^']+)'\s+and\s+'(?<to>[^']+)'",
            System.Text.RegularExpressions.RegexOptions.Compiled | System.Text.RegularExpressions.RegexOptions.IgnoreCase);

        public static string NormalizeTypeName(string typeName)
        {
            if (string.IsNullOrEmpty(typeName)) return string.Empty;
            string clean = typeName.Trim();
            // Repeatedly remove bracketed metadata like [VirtualIDEAssembly...] or [C:\...\RopeController.cs(18)]
            while (clean.Contains("["))
            {
                string prev = clean;
                clean = System.Text.RegularExpressions.Regex.Replace(clean, @"\s*\[[^\[\]]*\]", "");
                if (clean == prev) break;
            }
            clean = System.Text.RegularExpressions.Regex.Replace(clean, @"\s*\(in\s+[^)]*\)", "");
            clean = clean.Trim();
            if (clean.StartsWith("global::")) clean = clean.Substring(8);
            return clean;
        }

        public static bool IsFalsePositiveDuplicateTypeDiagnostic(Diagnostic diag)
        {
            if (diag == null) return false;
            if (diag.Id == "CS1503" || diag.Id == "CS0029" || diag.Id == "CS0266" || diag.Id == "CS0039")
            {
                string msg = diag.GetMessage(System.Globalization.CultureInfo.InvariantCulture);
                var match = s_CannotConvertRegex.Match(msg);
                if (match.Success)
                {
                    string fromType = NormalizeTypeName(match.Groups["from"].Value).TrimEnd('?');
                    string toType = NormalizeTypeName(match.Groups["to"].Value).TrimEnd('?');

                    // Strictly require that the fully qualified type names are identical (e.g. Tensio.RopeController == Tensio.RopeController).
                    // If namespaces differ (e.g. MyProject.UI.Button vs UnityEngine.UI.Button), fromType != toType, so genuine errors are NEVER hidden.
                    if (!string.IsNullOrEmpty(fromType) && !string.IsNullOrEmpty(toType) && fromType == toType)
                    {
                        return true;
                    }
                }
            }
            else if (diag.Id == "CS0019" || diag.Id == "CS0034")
            {
                string msg = diag.GetMessage(System.Globalization.CultureInfo.InvariantCulture);
                var match = s_OperatorDuplicateTypeRegex.Match(msg);
                if (match.Success)
                {
                    string fromType = NormalizeTypeName(match.Groups["from"].Value).TrimEnd('?');
                    string toType = NormalizeTypeName(match.Groups["to"].Value).TrimEnd('?');

                    if (!string.IsNullOrEmpty(fromType) && !string.IsNullOrEmpty(toType) && fromType == toType)
                    {
                        return true;
                    }
                }
            }
            return false;
        }

        private static readonly DiagnosticDescriptor s_UnityNameDescriptor = new DiagnosticDescriptor(
            UnityStringContext.DiagnosticId, "Unknown Unity name", "{0}", "Unity", DiagnosticSeverity.Warning, true);

        private static readonly Dictionary<string, DiagnosticDescriptor> s_UnityAnalyzerDescriptors = new Dictionary<string, DiagnosticDescriptor>();

        private static DiagnosticDescriptor UnityAnalyzerDescriptor(string id)
        {
            lock (s_UnityAnalyzerDescriptors)
            {
                if (!s_UnityAnalyzerDescriptors.TryGetValue(id, out var descriptor))
                {
                    descriptor = new DiagnosticDescriptor(id, "Unity", "{0}", "Unity", DiagnosticSeverity.Warning, true);
                    s_UnityAnalyzerDescriptors[id] = descriptor;
                }
                return descriptor;
            }
        }

        /// <param name="unityNames">When set, string literals naming tags/layers/scenes/... are checked against it.</param>
        /// <param name="unityAnalyzers">Also report the FZU010-FZU015 Unity analyzer warnings.</param>
        public Task<List<Diagnostic>> GetDiagnosticsAsync(CancellationToken cancellationToken = default, UnityProjectSnapshot unityNames = null, bool unityAnalyzers = false)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                if (state == null || state.Model == null) return new List<Diagnostic>();

                // Only this document's diagnostics: the compilation may hold every file of the assembly.
                List<Diagnostic> allDiags;
                try
                {
                    allDiags = state.Model.GetDiagnostics(cancellationToken: cancellationToken)
                        .Where(d => (d.Severity == DiagnosticSeverity.Error || d.Severity == DiagnosticSeverity.Warning) && d.Location.SourceTree == state.Tree)
                        .ToList();
                }
                catch (OperationCanceledException)
                {
                    return new List<Diagnostic>();
                }

                var falsePositiveSpans = new List<Microsoft.CodeAnalysis.Text.TextSpan>();
                var filtered = new List<Diagnostic>();

                foreach (var d in allDiags)
                {
                    if (IsFalsePositiveDuplicateTypeDiagnostic(d))
                    {
                        falsePositiveSpans.Add(d.Location.SourceSpan);
                    }
                    else
                    {
                        filtered.Add(d);
                    }
                }

                // Only remove CS1502 if the method call contains false positive arguments AND does not contain any other real errors
                if (falsePositiveSpans.Count > 0)
                {
                    filtered.RemoveAll(d => d.Id == "CS1502" 
                        && falsePositiveSpans.Any(span => d.Location.SourceSpan.Contains(span) || d.Location.SourceSpan.OverlapsWith(span))
                        && !filtered.Any(other => other.Severity == DiagnosticSeverity.Error && other.Id != "CS1502" && (d.Location.SourceSpan.Contains(other.Location.SourceSpan) || d.Location.SourceSpan.OverlapsWith(other.Location.SourceSpan))));
                }

                if (unityNames != null && !cancellationToken.IsCancellationRequested)
                {
                    foreach (var issue in UnityStringContext.Validate(state.Tree.GetRoot(cancellationToken), state.Model, unityNames))
                        filtered.Add(Diagnostic.Create(s_UnityNameDescriptor, Location.Create(state.Tree, issue.Span), issue.Message));
                }

                if (unityAnalyzers && !cancellationToken.IsCancellationRequested)
                {
                    foreach (var issue in UnityAnalyzers.Analyze(state.Tree.GetRoot(cancellationToken), state.Model, cancellationToken))
                        filtered.Add(Diagnostic.Create(UnityAnalyzerDescriptor(issue.Id), Location.Create(state.Tree, issue.Span), issue.Message));
                }

                return filtered;
            });
        }

        public Task<Location> GetDefinitionLocationAsync(int caretPosition)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                if (state == null || state.Tree == null || state.Model == null)
                    return Location.None;

                var root = state.Tree.GetRoot();
                if (caretPosition < 0 || caretPosition > root.FullSpan.End) return Location.None;

                var node = root.FindToken(caretPosition).Parent;
                if (node == null) return Location.None;

                var symbolInfo = state.Model.GetSymbolInfo(node);
                var symbol = symbolInfo.Symbol ?? symbolInfo.CandidateSymbols.FirstOrDefault();

                // If the user clicked the declaration itself
                if (symbol == null)
                    symbol = state.Model.GetDeclaredSymbol(node);

                if (symbol == null && caretPosition > 0)
                {
                    var prevNode = root.FindToken(caretPosition - 1).Parent;
                    if (prevNode != null && prevNode != node)
                    {
                        symbolInfo = state.Model.GetSymbolInfo(prevNode);
                        symbol = symbolInfo.Symbol ?? symbolInfo.CandidateSymbols.FirstOrDefault();
                        if (symbol == null)
                            symbol = state.Model.GetDeclaredSymbol(prevNode);
                    }
                }

                if (symbol != null)
                {
                    var syntaxRef = symbol.DeclaringSyntaxReferences.FirstOrDefault();
                    if (syntaxRef != null)
                        return syntaxRef.GetSyntax().GetLocation();

                    var location = symbol.Locations.FirstOrDefault();
                    if (location != null && location.IsInSource)
                        return location;
                }

                return Location.None;
            });
        }

        public sealed class SignatureHelpInfo
        {
            /// <summary>Every overload as rich text, with the parameter at the caret highlighted.</summary>
            public List<string> Overloads = new List<string>();
            /// <summary>The overload the call binds to (or the first one that fits the arguments).</summary>
            public int Active;
        }

        public Task<SignatureHelpInfo> GetSignatureHelpAsync(int caretPosition)
        {
            return Task.Run(() =>
            {
                var state = _currentState;
                if (state == null || state.Tree == null || state.Model == null)
                    return null;

                var root = state.Tree.GetRoot();
                if (caretPosition < 0 || caretPosition > root.FullSpan.End) return null;

                var token = root.FindToken(caretPosition);
                if (token.Parent == null || (!token.Parent.AncestorsAndSelf().OfType<InvocationExpressionSyntax>().Any() && !token.Parent.AncestorsAndSelf().OfType<ObjectCreationExpressionSyntax>().Any()))
                {
                    if (caretPosition > 0)
                    {
                        token = root.FindToken(caretPosition - 1);
                    }
                }

                var invocation = token.Parent?.AncestorsAndSelf().OfType<InvocationExpressionSyntax>().FirstOrDefault(i => i.ArgumentList.Span.IntersectsWith(caretPosition));
                var objectCreation = invocation == null ? token.Parent?.AncestorsAndSelf().OfType<ObjectCreationExpressionSyntax>().FirstOrDefault(o => o.ArgumentList != null && o.ArgumentList.Span.IntersectsWith(caretPosition)) : null;
                if (invocation == null && objectCreation == null) return null;

                var argList = invocation != null ? invocation.ArgumentList : objectCreation.ArgumentList;
                if (argList == null || !argList.Span.IntersectsWith(caretPosition)) return null;

                var symbolInfo = invocation != null ? state.Model.GetSymbolInfo(invocation.Expression) : state.Model.GetSymbolInfo(objectCreation);
                var bound = symbolInfo.Symbol as IMethodSymbol ?? symbolInfo.CandidateSymbols.OfType<IMethodSymbol>().FirstOrDefault();

                List<IMethodSymbol> overloads;
                if (invocation != null)
                    overloads = state.Model.GetMemberGroup(invocation.Expression).OfType<IMethodSymbol>().ToList();
                else
                    overloads = (state.Model.GetTypeInfo(objectCreation).Type as INamedTypeSymbol)?.InstanceConstructors.Where(c => c.DeclaredAccessibility == Accessibility.Public).Cast<IMethodSymbol>().ToList() ?? new List<IMethodSymbol>();
                if (overloads.Count == 0 && bound != null) overloads.Add(bound);
                if (overloads.Count == 0) return null;

                int argumentIndex = 0;
                var arguments = argList.Arguments;
                for (int i = 0; i < arguments.Count; i++)
                {
                    if (caretPosition > arguments[i].Span.End) argumentIndex = i + 1;
                }

                var info = new SignatureHelpInfo();
                int active = bound != null ? overloads.FindIndex(o => SymbolEqualityComparer.Default.Equals(o.OriginalDefinition, bound.OriginalDefinition)) : -1;
                if (active < 0) active = Math.Max(0, overloads.FindIndex(o => o.Parameters.Length >= arguments.Count));
                info.Active = active;

                foreach (var method in overloads)
                {
                    int activeParam = method.Parameters.Length == 0 ? -1 : Math.Min(argumentIndex, method.Parameters.Length - 1);
                    if (activeParam >= 0 && argumentIndex >= method.Parameters.Length && !method.Parameters[method.Parameters.Length - 1].IsParams) activeParam = -1;
                    var paramList = method.Parameters.Select((p, idx) =>
                    {
                        string pStr = (p.IsParams ? "params " : "") + $"{p.Type.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat)} {p.Name}";
                        if (p.HasExplicitDefaultValue) pStr += " = " + (p.ExplicitDefaultValue == null ? "null" : p.ExplicitDefaultValue is bool b ? (b ? "true" : "false") : p.ExplicitDefaultValue is string str ? "\"" + str + "\"" : Convert.ToString(p.ExplicitDefaultValue, System.Globalization.CultureInfo.InvariantCulture));
                        pStr = pStr.Replace("<", "<\u200B");
                        return idx == activeParam ? $"<b><color=#FFD700>{pStr}</color></b>" : pStr;
                    });
                    string methodName = invocation != null ? method.Name : (method.ContainingType?.Name ?? method.Name);
                    string returnType = invocation != null ? (method.ReturnsVoid ? "void " : method.ReturnType.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat).Replace("<", "<\u200B") + " ") : "";
                    info.Overloads.Add($"{returnType}{methodName}({string.Join(", ", paramList)})");
                }
                return info;
            });
        }

